  function modelPanel() {
    var m = DATA.model;
    var fit = m.fit;
    var factors = Object.keys(DATA.cat_factors)
      .filter(function (k) { return k !== 'default'; })
      .map(function (k) { return { name: k, factor: DATA.cat_factors[k] }; })
      .sort(function (a, b) { return b.factor - a.factor || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0); });
    return el('section', { class: 'panel model' },
      el('h2', { text: 'How implied value is computed' }),
      el('p', { class: 'sub', text: 'Every row is scored by one function of the snapshot figures. No protocol name is special-cased, and no row is hand-picked.' }),
      el('div', { class: 'formula' },
        'implied = round( 10^(A + B x log10(tvl)) x catFactor x (1 + clamp(change_7d, ' + m.growth.floor + ', ' + m.growth.cap + ') / 100 x ' + m.growth.weight + ') x (' + m.maturity.floor + ' + min(age_days, ' + m.maturity.days + ') / ' + m.maturity.days + ' x ' + m.maturity.range + ') x (1 + ' + m.chain.per_extra_chain + ' x min(chains - 1, ' + m.chain.max_extra + ')) )'
      ),
      el('p', { class: 'sub', text: 'The power law is fitted on this snapshot: log10(mcap) = ' + fit.intercept.toFixed(3) + ' + ' + fit.slope.toFixed(3) + ' x log10(tvl), over ' + fit.n + ' token-bearing protocols with a market cap above zero (R2 ' + fit.r2.toFixed(3) + '). Value scales sublinearly with TVL: the fitted multiple falls from about 0.67x at $5M of TVL to about 0.03x at $2.75B. The category factor is the category\u2019s median log-residual against that fit, used only when at least 3 protocols in the category carry a market cap, and clamped to [0.5, 2.0]; every other category scores 1.0. Growth is clamped to [-50, +100] percent so one extreme week cannot top the board, maturity runs 0.70 to 1.00 over three years, and each extra chain adds 2 percent up to 10 percent.' }),
      el('div', { class: 'factor-table' }, factors.map(function (f) {
        return el('span', null, f.name + ' ', el('b', { text: fmtMult(f.factor) }));
      })),
      el('p', { class: 'sub', text: 'Implied value is an estimate, not a price. The model does not predict whether or when a token launches, and a protocol that records no token may still have one its DefiLlama record does not carry. Age is the time since the protocol was first listed, the best record of how long it has run with no token; an unlisted age uses ' + m.maturity.unknown_age_days + ' days.' })
    );
  }

